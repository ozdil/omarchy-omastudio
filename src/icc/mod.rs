#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct IccProfileInfo {
    pub id: String,
    pub name: String,
    pub description: String,
    pub path: String,
    pub is_wide_gamut: bool,
    pub is_default: bool,
}

pub fn get_icc_directories() -> Vec<PathBuf> {
    let mut dirs = Vec::new();
    let home = env::var("HOME").unwrap_or_else(|_| ".".to_string());
    
    // User OmaStudio ICC folder
    dirs.push(PathBuf::from(&home).join(".local/share/omastudio/icc"));
    // Project bundled assets (source checkout)
    dirs.push(PathBuf::from("assets/icc"));
    // Bundled assets of installed builds: <prefix>/share/omastudio/icc next to <prefix>/bin
    if let Ok(exe) = env::current_exe()
        && let Some(prefix) = exe.parent().and_then(|bin| bin.parent())
    {
        dirs.push(prefix.join("share/omastudio/icc"));
    }
    dirs.push(PathBuf::from("/usr/share/omastudio/icc"));
    // System Ghostscript ICC folder
    dirs.push(PathBuf::from("/usr/share/ghostscript/iccprofiles"));
    // System color ICC folder
    dirs.push(PathBuf::from("/usr/share/color/icc"));

    dirs
}

pub fn list_icc_profiles() -> Vec<IccProfileInfo> {
    let mut profiles = Vec::new();
    let mut seen_ids = std::collections::HashSet::new();

    // Built-in profiles: generated by lcms2, always available
    let builtins = [
        ("sRGB", "sRGB (IEC 61966-2.1)", "Standard gamut for web and general displays", false, true),
        ("DisplayP3", "Display P3", "Modern wide-gamut displays and phones (P3 D65)", true, false),
        ("AdobeRGB1998", "Adobe RGB (1998)", "Wide-gamut standard for high-end photography & print", true, false),
        ("ProPhotoRGB", "ProPhoto RGB (ROMM)", "Ultra-wide 16-bit master archival working space", true, false),
        ("Rec2020", "Rec. 2020", "UHD video and HDR mastering primaries (BT.2020)", true, false),
    ];
    for (id, name, desc, wide, def) in builtins {
        seen_ids.insert(id.to_lowercase());
        profiles.push(IccProfileInfo {
            id: id.to_string(),
            name: name.to_string(),
            description: desc.to_string(),
            path: format!("builtin:{}", id),
            is_wide_gamut: wide,
            is_default: def,
        });
    }

    // Other standard profiles, shipped as files
    let standards = [
        ("scRGB_Linear", "scRGB Linear", "High Dynamic Range (HDR) linear color space", true, false),
        ("e-sRGB", "e-sRGB Extended", "Extended gamut sRGB with extended dynamic range", true, false),
    ];

    for (id, name, desc, wide, def) in standards {
        if let Some(path) = resolve_icc_path(id) {
            seen_ids.insert(id.to_lowercase());
            profiles.push(IccProfileInfo {
                id: id.to_string(),
                name: name.to_string(),
                description: desc.to_string(),
                path: path.to_string_lossy().to_string(),
                is_wide_gamut: wide,
                is_default: def,
            });
        }
    }

    // Scan directories for additional custom user ICC profiles
    for dir in get_icc_directories() {
        if let Ok(entries) = fs::read_dir(dir) {
            for entry in entries.flatten() {
                let path = entry.path();
                if path.is_file()
                    && let Some(ext) = path.extension().and_then(|s| s.to_str())
                {
                    let ext_lower = ext.to_lowercase();
                    if (ext_lower == "icc" || ext_lower == "icm")
                        && let Some(stem) = path.file_stem().and_then(|s| s.to_str())
                    {
                        let id_lower = stem.to_lowercase();
                        // Files of the built-in spaces (srgb.icc, a98.icc...) are covered above
                        if builtin_space(stem).is_none() && !seen_ids.contains(&id_lower) {
                            seen_ids.insert(id_lower);
                            profiles.push(IccProfileInfo {
                                id: stem.to_string(),
                                name: stem.replace('_', " "),
                                description: "Custom ICC Color Profile".to_string(),
                                path: path.to_string_lossy().to_string(),
                                is_wide_gamut: true,
                                is_default: false,
                            });
                        }
                    }
                }
            }
        }
    }

    profiles
}

pub fn resolve_icc_path(name_or_id: &str) -> Option<PathBuf> {
    let lower = name_or_id.to_lowercase();

    // Direct path check
    let direct = Path::new(name_or_id);
    if direct.exists() && direct.is_file() {
        return Some(direct.to_path_buf());
    }

    for dir in get_icc_directories() {
        if !dir.exists() {
            continue;
        }

        // Exact match
        let candidate = dir.join(format!("{}.icc", name_or_id));
        if candidate.exists() {
            return Some(candidate);
        }
        let candidate_icm = dir.join(format!("{}.icm", name_or_id));
        if candidate_icm.exists() {
            return Some(candidate_icm);
        }

        // Case-insensitive scan
        if let Ok(entries) = fs::read_dir(&dir) {
            for entry in entries.flatten() {
                let p = entry.path();
                if let Some(stem) = p.file_stem().and_then(|s| s.to_str())
                    && stem.to_lowercase() == lower
                {
                    return Some(p);
                }
            }
        }
    }

    // Fallbacks for standard names
    if lower.contains("srgb") {
        let fallback = PathBuf::from("/usr/share/ghostscript/iccprofiles/srgb.icc");
        if fallback.exists() { return Some(fallback); }
    } else if lower.contains("adobe") || lower.contains("a98") {
        let fallback = PathBuf::from("/usr/share/ghostscript/iccprofiles/a98.icc");
        if fallback.exists() { return Some(fallback); }
    } else if lower.contains("prophoto") || lower.contains("romm") {
        let fallback = PathBuf::from("/usr/share/ghostscript/iccprofiles/rommrgb.icc");
        if fallback.exists() { return Some(fallback); }
    }

    None
}

/// Standard RGB spaces whose ICC profiles the engine builds itself with lcms2, so
/// exports never depend on profile files or exiftool being installed.
pub const BUILTIN_PROFILES: [(&str, OutputColorSpace); 5] = [
    ("sRGB", OutputColorSpace::Srgb),
    ("DisplayP3", OutputColorSpace::DisplayP3),
    ("AdobeRGB1998", OutputColorSpace::AdobeRgb),
    ("ProPhotoRGB", OutputColorSpace::ProPhotoRgb),
    ("Rec2020", OutputColorSpace::Rec2020),
];

/// Largest ICC file accepted from disk; real RGB profiles are well under 4 MiB.
const MAX_ICC_BYTES: usize = 16 * 1024 * 1024;

/// Maps a profile id from the export dialog to a built-in space. Only exact names
/// match, so "scRGB_Linear" or "e-sRGB" files are not mistaken for sRGB.
pub fn builtin_space(name: &str) -> Option<OutputColorSpace> {
    let n = name.to_lowercase().replace([' ', '-', '_', '.', '(', ')'], "");
    let n = n.strip_suffix("icc").or_else(|| n.strip_suffix("icm")).unwrap_or(&n);
    match n {
        "srgb" | "srgbiec6196621" => Some(OutputColorSpace::Srgb),
        "displayp3" | "p3" | "p3d65" => Some(OutputColorSpace::DisplayP3),
        "adobergb1998" | "adobergb" | "a98" | "a98rgb" => Some(OutputColorSpace::AdobeRgb),
        "prophotorgb" | "prophoto" | "romm" | "rommrgb" => Some(OutputColorSpace::ProPhotoRgb),
        "rec2020" | "bt2020" | "itur2020" | "rec2020rgb" => Some(OutputColorSpace::Rec2020),
        _ => None,
    }
}

fn xy(x: f64, y: f64) -> CIExyY {
    CIExyY { x, y, Y: 1.0 }
}

/// Red, green and blue primaries and the white point, as CIE xy.
pub type Primaries = ([(f64, f64); 3], (f64, f64));

/// Primaries and white point of a built-in space.
pub fn primaries(space: OutputColorSpace) -> Primaries {
    let d65 = (0.3127, 0.3290);
    match space {
        OutputColorSpace::Srgb => ([(0.640, 0.330), (0.300, 0.600), (0.150, 0.060)], d65),
        OutputColorSpace::DisplayP3 => ([(0.680, 0.320), (0.265, 0.690), (0.150, 0.060)], d65),
        OutputColorSpace::AdobeRgb => ([(0.640, 0.330), (0.210, 0.710), (0.150, 0.060)], d65),
        OutputColorSpace::ProPhotoRgb => ([(0.7347, 0.2653), (0.1596, 0.8404), (0.0366, 0.0001)], (0.3457, 0.3585)),
        OutputColorSpace::Rec2020 => ([(0.708, 0.292), (0.170, 0.797), (0.131, 0.046)], d65),
    }
}

/// ACES AP1 primaries and the ACES white point (ACEScg).
pub const ACES_AP1: Primaries =
    ([(0.713, 0.293), (0.165, 0.830), (0.128, 0.044)], (0.32168, 0.33767));

fn rgb_profile(description: &str, prim: Primaries, curve: &ToneCurve) -> Profile {
    let (p, w) = prim;
    let triple = CIExyYTRIPLE { Red: xy(p[0].0, p[0].1), Green: xy(p[1].0, p[1].1), Blue: xy(p[2].0, p[2].1) };
    let mut profile = Profile::new_rgb(&xy(w.0, w.1), &triple, &[curve, curve, curve])
        .expect("valid RGB primaries");
    set_text_tags(&mut profile, description);
    profile
}

/// Builds the ICC profile of a built-in space: its primaries, white point and the
/// display curve the pipeline encodes that space with.
pub fn builtin_profile(space: OutputColorSpace) -> Profile {
    let srgb_curve = [2.4, 1.0 / 1.055, 0.055 / 1.055, 1.0 / 12.92, 0.04045];
    let (description, curve) = match space {
        OutputColorSpace::Srgb => {
            let mut profile = Profile::new_srgb();
            set_text_tags(&mut profile, "sRGB IEC61966-2.1 (OmaStudio)");
            return profile;
        }
        OutputColorSpace::DisplayP3 => ("Display P3 (OmaStudio)", ToneCurve::new_parametric(4, &srgb_curve)),
        OutputColorSpace::AdobeRgb => (
            "Adobe RGB (1998) compatible (OmaStudio)",
            ToneCurve::new_parametric(1, &[2.199_218_75]),
        ),
        OutputColorSpace::ProPhotoRgb => (
            "ProPhoto RGB (ROMM) compatible (OmaStudio)",
            ToneCurve::new_parametric(1, &[1.8]),
        ),
        OutputColorSpace::Rec2020 => (
            "ITU-R BT.2020 (OmaStudio)",
            ToneCurve::new_parametric(4, &[1.0 / 0.45, 1.0 / 1.099, 0.099 / 1.099, 1.0 / 4.5, 0.081]),
        ),
    };
    // Parametric curves with these constant parameters cannot fail to build
    let curve = curve.expect("valid parametric curve");
    rgb_profile(description, primaries(space), &curve)
}

/// The same primaries as [`builtin_profile`] with a linear (gamma 1.0) curve, for
/// scene-referred float output such as OpenEXR.
pub fn linear_profile(space: OutputColorSpace) -> Profile {
    let name = match space {
        OutputColorSpace::Srgb => "Linear Rec.709 (OmaStudio)",
        OutputColorSpace::DisplayP3 => "Linear Display P3 (OmaStudio)",
        OutputColorSpace::AdobeRgb => "Linear Adobe RGB (1998) compatible (OmaStudio)",
        OutputColorSpace::ProPhotoRgb => "Linear ProPhoto RGB compatible (OmaStudio)",
        OutputColorSpace::Rec2020 => "Linear Rec.2020 (OmaStudio)",
    };
    rgb_profile(name, primaries(space), &ToneCurve::new(1.0))
}

/// ACEScg: AP1 primaries, ACES white, linear.
pub fn acescg_profile() -> Profile {
    rgb_profile("ACEScg (OmaStudio)", ACES_AP1, &ToneCurve::new(1.0))
}

fn set_text_tags(profile: &mut Profile, description: &str) {
    let mut desc = MLU::new(1);
    desc.set_text_ascii(description, Locale::none());
    profile.write_tag(TagSignature::ProfileDescriptionTag, Tag::MLU(&desc));
    let mut copyright = MLU::new(1);
    copyright.set_text_ascii("No copyright, use freely", Locale::none());
    profile.write_tag(TagSignature::CopyrightTag, Tag::MLU(&copyright));
}

/// Where an export's pixels end up and the profile embedded with them.
pub enum ExportProfile {
    /// A space the decoder can render into directly.
    Builtin(OutputColorSpace),
    /// ACEScg (linear AP1). Rendered in ProPhoto RGB and converted with lcms2.
    AcesCg,
    /// An RGB profile from disk (printer, lab, custom display). Pixels are rendered in
    /// a built-in space first and converted with lcms2.
    Custom { name: String, profile: Profile, bytes: Vec<u8> },
}

impl ExportProfile {
    /// Resolves the export dialog's profile id: a built-in space by name, else an
    /// RGB ICC file found by [`resolve_icc_path`].
    pub fn resolve(name: &str) -> Result<Self, String> {
        if let Some(space) = builtin_space(name) {
            return Ok(Self::Builtin(space));
        }
        let n = name.to_lowercase().replace([' ', '-', '_', '.', '(', ')'], "");
        if n == "acescg" || n == "acescgap1" || n == "ap1" {
            return Ok(Self::AcesCg);
        }
        let path = resolve_icc_path(name).ok_or_else(|| format!("ICC profile not found: {}", name))?;
        let bytes = crate::security::read_secure_file(&path, MAX_ICC_BYTES)
            .map_err(|e| format!("Could not read ICC profile {}: {}", path.display(), e))?;
        let profile = Profile::new_icc(&bytes)
            .map_err(|e| format!("Invalid ICC profile {}: {}", path.display(), e))?;
        if profile.color_space() != ColorSpaceSignature::RgbData {
            return Err(format!(
                "{} is not an RGB profile; only RGB output profiles can be used for export",
                path.display()
            ));
        }
        Ok(Self::Custom { name: name.to_string(), profile, bytes })
    }

    /// Bytes to embed in the exported file.
    pub fn icc_bytes(&self) -> Result<Vec<u8>, String> {
        match self {
            Self::Builtin(space) => builtin_profile(*space)
                .icc()
                .map_err(|e| format!("Could not serialise ICC profile: {}", e)),
            Self::AcesCg => acescg_profile()
                .icc()
                .map_err(|e| format!("Could not serialise ICC profile: {}", e)),
            Self::Custom { bytes, .. } => Ok(bytes.clone()),
        }
    }

    /// The linear profile with this target's primaries, for float output (OpenEXR).
    /// Primaries and white point go with it for the file's chromaticities.
    pub fn linear(&self) -> Result<(Profile, Primaries), String> {
        match self {
            Self::Builtin(space) => Ok((linear_profile(*space), primaries(*space))),
            Self::AcesCg => Ok((acescg_profile(), ACES_AP1)),
            Self::Custom { name, .. } => Err(format!(
                "OpenEXR is scene-linear and needs a built-in colour space; {} is a display or print profile",
                name
            )),
        }
    }
}

/// ICC bytes of a profile to soft-proof against: a built-in space, ACEScg, or a file
/// found by [`resolve_icc_path`]. Unlike export, print profiles (CMYK, grey) are
/// accepted: proofing only needs the device's gamut, never its pixels.
pub fn proof_profile_bytes(name: &str) -> Result<Vec<u8>, String> {
    if let Some(space) = builtin_space(name) {
        return builtin_profile(space).icc().map_err(|e| format!("Could not serialise ICC profile: {}", e));
    }
    let n = name.to_lowercase().replace([' ', '-', '_', '.', '(', ')'], "");
    if n == "acescg" || n == "acescgap1" || n == "ap1" {
        return acescg_profile().icc().map_err(|e| format!("Could not serialise ICC profile: {}", e));
    }
    let path = resolve_icc_path(name).ok_or_else(|| format!("ICC profile not found: {}", name))?;
    let bytes = crate::security::read_secure_file(&path, MAX_ICC_BYTES)
        .map_err(|e| format!("Could not read ICC profile {}: {}", path.display(), e))?;
    let profile = Profile::new_icc(&bytes).map_err(|e| format!("Invalid ICC profile {}: {}", path.display(), e))?;
    match profile.color_space() {
        ColorSpaceSignature::RgbData | ColorSpaceSignature::CmykData | ColorSpaceSignature::GrayData => Ok(bytes),
        _ => Err(format!("{} is not an RGB, CMYK or grey output profile", path.display())),
    }
}

/// Colour that marks pixels the proof profile cannot reproduce (a vivid magenta,
/// which photographs rarely contain)
const GAMUT_WARNING_RGB: [u16; 3] = [0xFFFF, 0x0000, 0xC0C0];

/// Soft-proofs an 8-bit sRGB preview in place: each pixel is shown as it would look
/// printed or exported with `proof_icc` and `intent`. With `gamut_warning`, pixels the
/// proof device cannot reproduce are painted [`GAMUT_WARNING_RGB`].
pub fn soft_proof_rgb8(pixels: &mut [u8], proof_icc: &[u8], intent: RenderingIntent, gamut_warning: bool) -> Result<(), String> {
    let mut context = ThreadContext::new();
    if gamut_warning {
        let mut codes = [0u16; 16];
        codes[..3].copy_from_slice(&GAMUT_WARNING_RGB);
        context.set_alarm_codes(codes);
    }
    let display: Profile<ThreadContext> = Profile::new_srgb_context(&context);
    let proof = Profile::new_icc_context(&context, proof_icc).map_err(|e| format!("Invalid proof profile: {}", e))?;
    let mut flags = Flags::NO_CACHE | Flags::SOFT_PROOFING;
    if gamut_warning {
        flags = flags | Flags::GAMUT_CHECK;
    }
    if intent != RenderingIntent::AbsoluteColorimetric {
        flags = flags | Flags::BLACKPOINT_COMPENSATION;
    }
    // sRGB -> proof device with the chosen intent, then proof device -> screen keeping
    // the device's white (relative colorimetric), as print previews do by default
    let transform: Transform<[u8; 3], [u8; 3], ThreadContext, _> = Transform::new_proofing_context(
        &context,
        &display,
        PixelFormat::RGB_8,
        &display,
        PixelFormat::RGB_8,
        &proof,
        intent.into(),
        Intent::RelativeColorimetric,
        flags,
    )
    .map_err(|e| format!("Could not build proofing transform: {}", e))?;
    let (rgb, _) = pixels.as_chunks_mut::<3>();
    rgb.par_chunks_mut(64 * 1024).for_each(|chunk| transform.transform_in_place(chunk));
    Ok(())
}

/// How lcms2 maps colours that a destination profile cannot hold.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RenderingIntent {
    Perceptual,
    #[default]
    RelativeColorimetric,
    Saturation,
    AbsoluteColorimetric,
}

impl From<RenderingIntent> for Intent {
    fn from(intent: RenderingIntent) -> Self {
        match intent {
            RenderingIntent::Perceptual => Intent::Perceptual,
            RenderingIntent::RelativeColorimetric => Intent::RelativeColorimetric,
            RenderingIntent::Saturation => Intent::Saturation,
            RenderingIntent::AbsoluteColorimetric => Intent::AbsoluteColorimetric,
        }
    }
}

/// Converts interleaved 16-bit RGB from `source` to `destination` in place, with
/// black point compensation (except for absolute colorimetric, where it does not apply).
pub fn convert_rgb16(
    pixels: &mut [u16],
    source: &Profile,
    destination: &Profile,
    intent: RenderingIntent,
) -> Result<(), String> {
    let flags = if intent == RenderingIntent::AbsoluteColorimetric {
        Flags::NO_CACHE
    } else {
        Flags::NO_CACHE | Flags::BLACKPOINT_COMPENSATION
    };
    // NO_CACHE keeps the transform free of shared state, so rayon can share it
    let transform: Transform<[u16; 3], [u16; 3], _, _> = Transform::new_flags_context(
        GlobalContext::new(),
        source,
        PixelFormat::RGB_16,
        destination,
        PixelFormat::RGB_16,
        intent.into(),
        flags,
    )
            .map_err(|e| format!("Could not build colour transform: {}", e))?;
    let (rgb, _) = pixels.as_chunks_mut::<3>();
    rgb.par_chunks_mut(64 * 1024).for_each(|chunk| transform.transform_in_place(chunk));
    Ok(())
}

/// Converts interleaved 16-bit RGB from `source` to float RGB in `destination`
/// (normally a linear profile from [`ExportProfile::linear`]).
pub fn convert_rgb16_to_f32(
    pixels: &[u16],
    source: &Profile,
    destination: &Profile,
    intent: RenderingIntent,
) -> Result<Vec<f32>, String> {
    let flags = if intent == RenderingIntent::AbsoluteColorimetric {
        Flags::NO_CACHE
    } else {
        Flags::NO_CACHE | Flags::BLACKPOINT_COMPENSATION
    };
    let transform: Transform<[u16; 3], [f32; 3], _, _> = Transform::new_flags_context(
        GlobalContext::new(),
        source,
        PixelFormat::RGB_16,
        destination,
        PixelFormat::RGB_FLT,
        intent.into(),
        flags,
    )
    .map_err(|e| format!("Could not build colour transform: {}", e))?;
    let (src, _) = pixels.as_chunks::<3>();
    let mut out = vec![[0.0f32; 3]; src.len()];
    out.par_chunks_mut(64 * 1024)
        .zip(src.par_chunks(64 * 1024))
        .for_each(|(dst, src)| transform.transform_pixels(src, dst));
    Ok(out.into_iter().flatten().collect())
}

#[cfg(test)]
mod proof_tests {
    use super::*;

    /// A narrow RGB device: its primaries sit halfway to the white point.
    fn narrow_profile() -> Vec<u8> {
        let ((p, w), half) = (primaries(OutputColorSpace::Srgb), |a: (f64, f64), w: (f64, f64)| ((a.0 + w.0) / 2.0, (a.1 + w.1) / 2.0));
        let narrow = ([half(p[0], w), half(p[1], w), half(p[2], w)], w);
        rgb_profile("narrow", narrow, &ToneCurve::new(2.2)).icc().unwrap()
    }

    #[test]
    fn proofing_against_srgb_changes_nothing_visible() {
        let mut px = vec![200u8, 40, 30, 20, 120, 220, 128, 128, 128];
        let before = px.clone();
        let srgb = builtin_profile(OutputColorSpace::Srgb).icc().unwrap();
        soft_proof_rgb8(&mut px, &srgb, RenderingIntent::RelativeColorimetric, true).unwrap();
        for (a, b) in px.iter().zip(&before) {
            assert!((*a as i32 - *b as i32).abs() <= 2, "{px:?} vs {before:?}");
        }
    }

    #[test]
    fn saturated_colours_outside_a_narrow_device_are_flagged() {
        let narrow = narrow_profile();
        // Pure red is far outside; mid grey is inside
        let mut px = vec![255u8, 0, 0, 128, 128, 128];
        soft_proof_rgb8(&mut px, &narrow, RenderingIntent::RelativeColorimetric, true).unwrap();
        assert_eq!(&px[..3], &[255, 0, 192]);
        assert!(px[3..].iter().all(|&v| (v as i32 - 128).abs() <= 3), "{px:?}");

        // Without the warning the red is shown as the device can print it: duller
        let mut px = vec![255u8, 0, 0];
        soft_proof_rgb8(&mut px, &narrow, RenderingIntent::RelativeColorimetric, false).unwrap();
        assert!(px[1] > 20 && px[2] > 20, "{px:?}");
    }
}
